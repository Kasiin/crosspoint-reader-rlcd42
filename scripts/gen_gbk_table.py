#!/usr/bin/env python3
"""Generate lib/Txt/GbkUnicodeTable.h: GBK double-byte -> Unicode BMP lookup.

Every (lead, trail) pair with lead in 0x81..0xFE and trail in 0x40..0xFE
(excluding 0x7F) is decoded with Python's gb18030 codec, whose two-byte range
is a superset of GBK. All mapped values are single BMP code points. Undefined
pairs would be stored as U+FFFD.

Usage: python scripts/gen_gbk_table.py
"""

import pathlib

LEAD_BASE = 0x81
LEAD_COUNT = 0xFE - 0x81 + 1  # 126
TRAILS = list(range(0x40, 0x7F)) + list(range(0x80, 0xFF))  # 190, excludes 0x7F

REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]
OUTPUT = REPO_ROOT / 'lib' / 'Txt' / 'GbkUnicodeTable.h'


def build_table() -> list[int]:
    values = []
    for lead in range(LEAD_BASE, 0xFF):
        for trail in TRAILS:
            try:
                char = bytes([lead, trail]).decode('gb18030')
                cp = ord(char)
                assert len(char) == 1 and cp <= 0xFFFF and cp != 0xFFFD
            except (UnicodeDecodeError, AssertionError):
                cp = 0xFFFD
            values.append(cp)
    return values


def main() -> None:
    values = build_table()
    rows = []
    # 14 entries per line matches clang-format's packing at the repo's 120-column limit.
    for i in range(0, len(values), 14):
        rows.append('    ' + ', '.join(f'0x{cp:04X}' for cp in values[i : i + 14]) + ',')
    content = f"""#pragma once

// Generated by scripts/gen_gbk_table.py - do not edit.
// Regenerate with: python scripts/gen_gbk_table.py
//
// GBK double-byte to Unicode lookup. Index: (lead - 0x81) * 190 + trail index,
// where trail index is (trail - 0x40) for trail < 0x7F and (trail - 0x41) for
// trail > 0x7F (0x7F is not a valid trail byte). All values are BMP code
// points; undefined pairs are U+FFFD.

#include <cstdint>

inline constexpr uint16_t GBK_UNICODE_TABLE[{len(values)}] = {{
{chr(10).join(rows)}
}};
"""
    OUTPUT.write_text(content, encoding='utf-8', newline='\n')
    print(f'Wrote {OUTPUT} ({len(values)} entries, {len(values) * 2} bytes)')


if __name__ == '__main__':
    main()
